"""Helper-call-site tests for the langgraph emitter (F-CR-04 CORE-LG-EMITTER).

These tests pin the wiring between :mod:`compilers.langgraph.state`'s emitted
``@tool`` bodies and the audit-trail mirror helper they call:

- The emitted source for every CACAO action / playbook-action step opens an
  OpenTelemetry span and appends an :class:`AuditRecord` to the surrounding
  trail inside it.
- The recorded attribute set carries the envelope contract: stable
  ``secops_ng.playbook.id`` / ``secops_ng.step.id`` / ``secops_ng.tool.name``
  keys plus the empty-string ``secops_ng.workflow.run_id`` compile-time
  placeholder (per Director's 2026-06-03 decision baked into the
  CORE-LG-EMITTER card body).
- No ``secops_ng.audit.ts`` attribute is emitted — timestamps remain runtime
  concerns surfaced via OTel spans.
- Replaying the same input is a no-op at the trail level (idempotency).
- The sovereign-stack guard holds: only ``opentelemetry`` is imported by the
  emitted source — no vendor SDK substrings, no hard-coded OTLP endpoint.

The tests deliberately *do not* compare against the committed goldens — the
goldens are stale on this PR and get regenerated by the CORE-LG-GOLDENS
sibling. Instead they ad-hoc compile-and-import the emitted source from a
synthetic playbook against a freshly-materialised ``_audit_mirror.py`` so the
helper call site itself is exercised end to end without depending on the
golden suite.
"""
