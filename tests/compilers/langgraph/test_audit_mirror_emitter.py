def _materialise_emitted_pkg(tmp_path: Path, name: str, playbook: dict):
    """Drop the emitted ``state_bindings.py`` + a fresh ``_audit_mirror.py``
    into a tmp package so the relative ``from ._audit_mirror import ...`` in
    the emitted source resolves cleanly."""
    pkg = tmp_path / name
    pkg.mkdir()
    (pkg / "__init__.py").write_text("", encoding="utf-8")
    (pkg / "_audit_mirror.py").write_text(render_audit_mirror_module(), encoding="utf-8")
    (pkg / "state_bindings.py").write_text(
        render_module(parse(playbook)), encoding="utf-8"
    )
    sys.path.insert(0, str(tmp_path))
    return importlib.import_module(f"{name}.state_bindings"), importlib.import_module(
        f"{name}._audit_mirror"
    )


@pytest.fixture
def emitted_modules(tmp_path: Path):
    name = "lg_emitter_audit_pkg"
    bindings_mod, mirror_mod = _materialise_emitted_pkg(
        tmp_path, name, _synthetic_playbook()
    )
    yield bindings_mod, mirror_mod
    sys.path.remove(str(tmp_path))
    for mod_name in (
        f"{name}.state_bindings",
        f"{name}._audit_mirror",
        name,
    ):
        sys.modules.pop(mod_name, None)


def _drive_emitted_coro(bindings_mod, mirror_mod, *, replays: int = 1):
    """Run the emitted ``enrich_finding`` coroutine N times and capture the
    audit trail snapshot from inside the same asyncio task — so the
    ContextVar binding the emitted code wrote is the one we read.

    The emitted body raises :class:`NotImplementedError` after the
    ``AuditTrail.current().append(...)`` call, so the helper invocation is
    observable even though the stub body is a deliberate ``NotImplementedError``.
    """
    tool_obj = bindings_mod.enrich_finding

    async def _runner():
        # The @tool decoration exposes the underlying coroutine on
        # ``.coroutine``; calling it directly keeps us in the current asyncio
        # task context so the ContextVar set by ``AuditTrail.current()``
        # inside the emitted body is visible when we snapshot below.
        for _ in range(replays):
            try:
                await tool_obj.coroutine(finding_id="f-1")
            except NotImplementedError:
                pass
        return mirror_mod.AuditTrail.current().snapshot()

    return asyncio.run(_runner())


def test_invoking_emitted_tool_appends_audit_record(emitted_modules) -> None:
    """Driving the emitted @tool stub appends one record with the bound envelope."""
    bindings_mod, mirror_mod = emitted_modules
    snap = _drive_emitted_coro(bindings_mod, mirror_mod)
    assert len(snap) == 1
    record = snap[0]
    assert record.span_name == f"tool.{_ACTION}"
    attrs = dict(record.attributes)
    assert attrs[SPAN_ATTR_PLAYBOOK_ID] == _PB_ID
    assert attrs[SPAN_ATTR_STEP_ID] == _ACTION
    assert attrs[SPAN_ATTR_TOOL_NAME] == "enrich_finding"
    # Envelope contract: empty-string placeholder, NO ts attribute.
    assert attrs[SPAN_ATTR_WORKFLOW_RUN_ID] == ""
    assert "secops_ng.audit.ts" not in attrs


def test_replaying_emitted_tool_is_idempotent(emitted_modules) -> None:
    """Re-driving the emitted @tool stub does not duplicate the audit row."""
    bindings_mod, mirror_mod = emitted_modules
    snap = _drive_emitted_coro(bindings_mod, mirror_mod, replays=3)
    assert len(snap) == 1, f"replay duplicated audit rows: snapshot size {len(snap)}"
