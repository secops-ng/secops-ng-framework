def test_emitted_tool_body_calls_audit_trail_append() -> None:
    """The emitted @tool body must call ``AuditTrail.current().append(...)``."""
    src = render_tool_bindings(tool_bindings(parse(_synthetic_playbook())))
    assert "AuditTrail.current().append(" in src
    assert "AuditRecord(span_name=" in src


def test_emitted_tool_attributes_include_workflow_run_id_placeholder() -> None:
    """Envelope contract: empty-string ``secops_ng.workflow.run_id`` is emitted."""
    src = render_tool_bindings(tool_bindings(parse(_synthetic_playbook())))
    # ``_py_repr`` uses ``repr`` so the attribute key and value render as
    # single-quoted Python literals.
    assert f"'{SPAN_ATTR_WORKFLOW_RUN_ID}': ''" in src


def test_emitted_tool_attributes_omit_timestamp() -> None:
    """No ``secops_ng.audit.ts`` attribute: timestamps stay runtime-only."""
    src = render_tool_bindings(tool_bindings(parse(_synthetic_playbook())))
    assert "secops_ng.audit.ts" not in src


def test_emitted_module_only_imports_opentelemetry_for_otel() -> None:
    """Sovereign-stack guard: only ``opentelemetry.*`` imports, no vendor SDK."""
    src = render_module(parse(_synthetic_playbook()))
    tree = ast.parse(src)
    otel_imports: list[str] = []
    for node in ast.walk(tree):
        if isinstance(node, ast.ImportFrom) and node.module:
            if node.module.startswith("opentelemetry"):
                otel_imports.append(node.module)
        elif isinstance(node, ast.Import):
            for alias in node.names:
                if alias.name.startswith("opentelemetry"):
                    otel_imports.append(alias.name)
    # At least one OTel import (the rendered ``from opentelemetry import trace``).
    assert any("opentelemetry" in m for m in otel_imports)
    # Vendor SDK substrings the linter would flag — none in emitted source.
    for forbidden in ("datadog", "newrelic", "elastic_apm", "dynatrace", "honeycomb"):
        assert forbidden not in src.lower()
    # No hard-coded OTLP endpoint URL.
    assert "http://" not in src
    assert "https://" not in src


